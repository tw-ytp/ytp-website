const canonSet = new Set<string>(CANON);

/** 單一 tag → 正規名（找不到別名就原樣回傳） */
export const canonTag = (t: string): string => ALIAS[t] ?? t;

/** 整組 tags → 正規化、去重、依 CANON 順序排列（非正規 tag 排在最後、保留原順序） */
export function normalizeTags(tags: string[]): string[] {
  const out: string[] = [];
  for (const t of tags.map(canonTag)) if (!out.includes(t)) out.push(t);
  const rank = (t: string) => { const i = CANON.indexOf(t as CanonTag); return i < 0 ? CANON.length : i; };
  return out.sort((a, b) => rank(a) - rank(b));
}

/** 篩選列用：只留正規 tag，依 CANON 順序 */
export const isCanon = (t: string): t is CanonTag => canonSet.has(t);
